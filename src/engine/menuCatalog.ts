const CHO_CONSONANTS = [
  'ㄱ', 'ㄲ', 'ㄴ', 'ㄷ', 'ㄸ', 'ㄹ', 'ㅁ', 'ㅂ', 'ㅃ',
  'ㅅ', 'ㅆ', 'ㅇ', 'ㅈ', 'ㅉ', 'ㅊ', 'ㅋ', 'ㅌ', 'ㅍ', 'ㅎ',
];

/**
 * Extract Korean initial consonants (초성) for instant 초성 search (e.g. "ㄷㅈ" -> "돼지국밥").
 */
export function extractChosung(text: string): string {
  let out = '';
  for (const ch of text) {
    const code = ch.charCodeAt(0);
    if (code >= 0xac00 && code <= 0xd7a3) {
      out += CHO_CONSONANTS[Math.floor((code - 0xac00) / (21 * 28))];
    } else if (!/\s/.test(ch)) {
      out += ch.toLowerCase();
    }
  }
  return out;
}

export function matchesMenuQuery(menuName: string, rawQuery: string): boolean {
  const q = rawQuery.trim().toLowerCase().replace(/\s+/g, '');
  if (!q) return true;
  const normalizedName = menuName.toLowerCase().replace(/\s+/g, '');
  if (normalizedName.includes(q)) return true;
  // Match Korean chosung queries like "ㄱㅊ" -> "김치찌개"
  if (/^[ㄱ-ㅎ]+$/.test(q)) {
    return extractChosung(normalizedName).includes(q);
  }
  return false;
}
